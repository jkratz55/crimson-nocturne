def _tile_ramps() -> dict[str, list[RGB]]:
    r: dict[str, list[RGB]] = {k: list(v) for k, v in RAMPS.items()}
    # Non-collision architecture on the playfield plane: stone one step
    # toward the indigo fog (Y 8..110 instead of 12..149).
    r["stone_d"] = aerial(RAMPS["stone"], desat=0.2, steps=0.6, fog_amt=0.15)
    # Wine-black polished marble (column shafts, floor fascia): the shared
    # MARBLE_DK plus one polished sheen tone on top.
    r["wine"] = list(RAMPS["marble_dk"]) + [(150, 126, 150)]
    # The column shaft's core shadow: wine 0 lifted to Y 18, still the
    # darkest band across the shaft (wine 1 terminator and reflected light,
    # Y 21, either side of it) but 12+ above the hero's Y ~6 contour.
    r["wine_core"] = [(24, 14, 26)]
    # Wrought iron (candle stands, chains, sconces).
    r["iron"] = [(12, 10, 20), (28, 26, 42), (48, 48, 68), (76, 78, 102), (116, 120, 148)]
    # Statue stone: ivory marble pushed back so it never outshines the hero.
    r["ivory_d"] = aerial(RAMPS["marble"], desat=0.3, steps=1.2, fog_amt=0.18)
    # Cobweb threads: cool pale lavender.
    r["web"] = [(70, 72, 100), (112, 114, 142), (156, 158, 184)]
    # The darkest scene value (docs/art_style.md), for the bottom vignette of the room.
    r["void"] = [(6, 4, 12)]
    # L5 foreground: the 1-px cool moon rim on near silhouettes, and the dark
