"""
Castle tileset for the Crimson Hall (SotN-style art pass).

Outputs, all regenerated by `build()` and never hand-edited:

- ``assets/tiles/castle_tiles.png``: the atlas, ``COLS`` tiles wide, a packed
  16 px grid with no margins or spacing.
- ``assets/tiles/castle_tiles.json``: the name -> atlas-coordinate table. It
  holds single tiles, world-periodic masonry *fields*, exposure *edge*
  overlays and multi-cell *pieces* (arches, piers, drapes...). The room builder
  (``tools/level_builder/build_castle_hall.py``) reads only this file, so the
  atlas layout can change freely.
- ``resources/tilesets/castle_tileset.tres``: generated from the same table,
  so collision can never drift from the art (it used to be hand-written).
- ``assets/tiles/castle_foreground.png``: the sparse L5 occluder plane (two
  chain-hung lanterns high up and three balustrade / urn tops rising from the
  bottom edge over the foundation, all near-black with a 1-px moon rim),
  described under ``"foreground"`` in the json so the builder emits it as a
  Parallax2D at scroll 1.3 over the actors.

Collision kinds are exactly the polygons the old hand-written tileset used:

- ``"solid"``: the full 16x16 square on physics layer 0 (collision layer 1,
  "world").
- ``"one_way"``: the top 5 px (y -8..-3), one-way, on physics layer 1
  (collision layer 256, "one_way").

Every other tile is decoration and has no physics.

Legacy slots: the 12 cells of the old 8x2 atlas keep their meaning and
collision kind (see ``LEGACY``), so a scene baked against the old atlas still
collides correctly before it is regenerated.

Rendering (docs/art_style.md, *Environment* and *Value plan*):

- Masonry is a height field: chamfered cut blocks with a pillow or rusticated
  face, chips and cracks, lit by ``LIGHT_ENV`` (top-left) through
  ``shade_heightmap`` and quantized into the hue-shifted 7-tone ``stone``
  ramp. Mortar is S0, the lit edges are S5/S6 and the shadowed edges S1/S2.
- Walls use a world-periodic 128x64 field, so any wall shape tiles
  seamlessly. Exposed faces get an overlay tile on a separate layer: a lit
  lip on top, an underside shadow, and arris lines on the sides.
- Ornament (frieze, pier capitals, arches, niche statue, banners, drapes) is
  drawn as large unique set pieces and sliced into 16x16 cells. Organic forms
  go through ``VolCanvas``, lit by the same ``LIGHT_ENV``.
- Value layering: collision tiles use the full ``stone`` and ``marble``
  ramps. Non-collision architecture on the 1.0 plane uses ``stone_d`` (the
  stone ramp pushed one step toward the indigo fog), so the walkable shapes
  always read brightest.
- The quiet band behind the run line (0-48 px above the floor) carries no
  lit stone and no crimson mass: pier shafts and bases are mid-value wine
  marble (faces wine 3; wine 2, the hero's contour value, only as 1-px
  grooves), candles with no surface right under them hang from chains so
  no fixture reaches below a candle's base,
  drape tails fall narrow and compressed to C1-C3, and the foundation
  course under the floor is the darkest, quietest collision art in the room
  (wine-black slabs, not an ivory/wine checker; see ASSUMPTIONS.md).
  Walkable lips top out at M4 and gold is an accent on the capitals.
"""
