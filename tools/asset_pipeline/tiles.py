# Arches
# --------------------------------------------------------------------------
ARCH_ZONE = 64          # px from the frieze bottom to the spring line
ARCH_PIECE_H = 80       # arch zone + the impost row


def arch_geometry(w: int, band: float, apex_in: float, spring: float,
                  ss: int = 1) -> dict[str, np.ndarray]:
    """Per-sample geometry of an arch whose extrados springs at x=0 and x=w:
    two-centred (pointed) when the rise exceeds the half span, otherwise
    segmental. Returns masks and the radial / along-arc coordinates (in 1x
    px units) on an `ss`-times supersampled grid."""
    X = (np.arange(w * ss, dtype=np.float64)[None, :] + 0.5) / ss
    Y = (np.arange(ARCH_PIECE_H * ss, dtype=np.float64)[:, None] + 0.5) / ss
    X, Y = np.broadcast_to(X, (ARCH_PIECE_H * ss, w * ss)), np.broadcast_to(Y, (ARCH_PIECE_H * ss, w * ss))
    mid = w / 2.0
    a = mid - band
    hrise = spring - apex_in
    left = X < mid
    Xm = np.where(left, X, w - X)            # mirror the right half onto the left
    if hrise >= a:
        c = (hrise * hrise - a * a) / (2.0 * a)
        r = a + c
        cxl, cy = mid + c, spring
        phi0 = 0.0
    else:
        r = (a * a + hrise * hrise) / (2.0 * hrise)
        cxl, cy = mid, spring + (r - hrise)
        phi0 = math.atan2(cy - spring, a)
    dist = np.hypot(Xm - cxl, Y - cy)
    phi = np.arctan2(cy - Y, cxl - Xm)
    phi_apex = math.atan2(math.sqrt(max(r * r - (cxl - mid) ** 2, 0.0)), cxl - mid)
    s = r * (phi - phi0)
    s_tot = r * (phi_apex - phi0)
    above = Y <= spring
    opening = np.where(above, dist < r, np.abs(X - mid) < a)
    ext = above & (dist < r + band)
    return {"X": X, "Y": Y, "dist": dist, "r": np.full_like(dist, r), "s": s,
            "s_tot": np.full_like(dist, s_tot), "opening": opening, "ext": ext, "above": above}


def _pool(a: np.ndarray, ss: int) -> np.ndarray:
    """Mean over each ss x ss block (supersampled -> 1x)."""
    h, w = a.shape[0] // ss, a.shape[1] // ss
    return np.asarray(a, np.float64).reshape(h, ss, w, ss).mean(axis=(1, 3))


def arch_piece(cells: int, seed: int) -> Canvas:
    """One arcade bay (cells x 5 rows): a moulded archivolt of voussoirs
    with a projecting keystone, ashlar spandrels up to the frieze, a dark
    soffit inside the arch (the opening itself is transparent), and in the
    bottom row the impost blocks that continue the pier capitals' abacus.
    The curved band is lit on a 4x supersampled height field and pooled,
    so its tone clusters follow the curve instead of stair-stepping."""
    w, h = cells * T, ARCH_PIECE_H
    band = 8.0 if cells >= 6 else 7.0
    ss = 4
    g4 = arch_geometry(w, band, apex_in=12.0, spring=float(ARCH_ZONE), ss=ss)
    rr = float(g4["r"][0, 0])
    st = float(g4["s_tot"][0, 0])
    n_v = max(2, int(round(st / 9.0)))
    step = st / (n_v + 0.5)

    def parts(g: dict[str, np.ndarray]) -> tuple[Mask, Mask, Mask, np.ndarray]:
        dist, s_, above_ = g["dist"], g["s"], g["above"]
        arch_ = g["ext"] & ~g["opening"]
        key_ = above_ & (s_ > n_v * step - 0.2) & (dist > rr - 2.2) & (dist < rr + band + 2.6)
        t_ = np.clip((dist - rr) / band, 0.0, 1.0)
        prof_ = np.select(
            [t_ < 0.2, t_ < 0.6, t_ < 0.68, t_ < 0.92],
            [0.45 + t_ / 0.2 * 0.55, np.ones_like(t_), np.full_like(t_, 0.72),
             0.72 + 0.5 * np.sin((t_ - 0.68) / 0.24 * math.pi)],
            0.95 - (t_ - 0.92) / 0.08 * 0.45)
        joints_ = np.zeros_like(t_, bool)
        for k in range(1, n_v + 1):
            joints_ |= np.abs(s_ - k * step) < 0.6
        return arch_, key_, joints_, prof_

    arch4, key4, joints4, prof4 = parts(g4)
    hgt4 = np.where(arch4, prof4 + 0.35, 0.0)
    hgt4 = np.where(arch4 & joints4 & ~key4, hgt4 - 0.55, hgt4)
    dk4 = inner_dist(key4) / ss
    hgt4 = np.where(key4, 1.45 + np.clip(dk4 / 1.4, 0, 1) * 0.35, hgt4)
    inten4 = lit(hgt4, 2.3 * ss)
    band4 = (arch4 | key4).astype(np.float64)
    cover = _pool(band4, ss)
    inten1 = _pool(inten4 * band4, ss) / np.maximum(cover, 1e-6)
    keyc = _pool(key4.astype(np.float64), ss)
    g = arch_geometry(w, band, apex_in=12.0, spring=float(ARCH_ZONE), ss=1)
    X, Y, dist = g["X"], g["Y"], g["dist"]
    opening, ext, above = g["opening"], g["ext"], g["above"]
    arch_any = cover >= 0.5
    key = arch_any & (keyc >= 0.5)
    arch = arch_any & ~key
    jointc = _pool((joints4 & arch4 & ~key4).astype(np.float64), ss)
    # spandrel ashlar outside the extrados, courses on the world's 8 px grid
    span_region = above & ~arch_any & ~ext & (Y < ARCH_ZONE)
    sp, _, _ = masonry(w, ARCH_ZONE, seed, "stone_d", courses=[16] * (ARCH_ZONE // 16),
                       widths=(24, 32, 40), split_p=0.15, wrap=False,
                       region=span_region[:ARCH_ZONE], bevel=1.2, rough_p=0.0, crack_p=0.05,
                       chip_p=0.15, grain=0.05, jitter=0.03, bias=-0.05, strength=1.4,
                       mortar_tone=1)
    cv = Canvas(w, h)
    cv.paste(sp)
    cv.shade(arch, inten1, "stone", bias=-0.06)
    cv.shade(key, inten1, "stone", bias=0.02)
    # keystone chamfer: lit top/left arris, shadowed bottom/right
    up, lf = np.roll(key, 1, 0), np.roll(key, 1, 1)
    dn, rt = np.roll(key, -1, 0), np.roll(key, -1, 1)
    cv.shift_tone(key & (~up | ~lf), 1)
    cv.shift_tone(key & (~dn | ~rt) & up & lf, -1)
    cv.fill(arch & (jointc >= 0.3), "stone_d", 1)
    cv.tidy()
    rr = float(g["r"][0, 0])
    # mortar line where the voussoirs meet the spandrel
    rim = above & ~arch_any & (dist < rr + band + 1.0) & (dist > rr)
    cv.fill(rim & (Y < ARCH_ZONE), "stone_d", 0)
    # soffit: the arch's thickness seen from below
    soffit = opening & above & (dist > rr - 3.0) & ~arch_any
    cv.fill(soffit, "stone_d", 1)
    cv.fill(soffit & (dist > rr - 1.0), "stone_d", 2)
    cv.fill(soffit & (dist <= rr - 2.0), "stone_d", 0)
    # imposts in the bottom row (continue the capital's abacus profile)
    sy = ARCH_ZONE
    imp_w = int(band) + 1
    for side in (0, 1):
        for i in range(imp_w):
            x = i if side == 0 else w - 1 - i
            cv.px(x, sy, "stone", 4)
            cv.px(x, sy + 1, "stone", 3)
            cv.px(x, sy + 2, "stone", 1)
        cons = Canvas(imp_w, 6)
        Xc, Yc = grid(imp_w, 6)
        edge = imp_w * (1.0 - Yc / 6.0) ** 1.2
        body = Xc < edge
        dd = inner_dist(body)
        hh = np.clip(dd / 1.5, 0, 1)
        cons.shade(body, lit(np.where(body, hh, 0), 2.4), "stone_d")
        cons.hline(0, imp_w - 1, 0, "stone_d", 0)
        if side == 1:
            cons.mat = cons.mat[:, ::-1].copy()
            cons.tone = cons.tone[:, ::-1].copy()
            # relight the mirrored console so its lit face stays top-left
            cons.shift_tone(cons.mat >= 0, -1)
        cv.paste(cons, 0 if side == 0 else w - imp_w, sy + 3)
    cv.tidy()
    return cv


def niche_wall(seed: int) -> Canvas:
    """Wall section with a statue niche (5 x 3 cells): ashlar around a
    pointed niche with a moulded frame, a fluted scallop hood, a veiled
    statue on a small plinth and a lit sill."""
    w, h = 5 * T, 3 * T
    X, Y = grid(w, h)
    cx, half, spring, apex, sill = 52.0, 14.0, 20.0, 3.0, 45.0
    hr = spring - apex
    c = (hr * hr - half * half) / (2 * half)
    rn = half + c
    left = X < cx
    dn = np.hypot(np.where(left, X - (cx + c), X - (cx - c)), Y - spring)
    inside = np.where(Y < spring, dn < rn, np.abs(X - cx) < half) & (Y < sill)
    frame = (np.where(Y < spring, dn < rn + 3.0, np.abs(X - cx) < half + 3.0) & (Y < sill + 1)) & ~inside
    wall_region = ~inside & ~frame
    # The niche wall is decor in front of nothing walkable, so it sits 1.5-2
    # steps under the collision walls beside it (faces stone_d 1-2, 1-px
    # stone_d 3 chamfers) and can never be mistaken for a wall to stand on.
    cv, _, _ = masonry(w, h, seed, "stone_d", courses=[8] * 6, widths=(12, 16, 20, 24), split_p=0.0,
                       wrap=False, region=wall_region, bevel=1.6, rough_p=0.1, crack_p=0.08, bias=-0.2)
    wall_px = wall_region & (cv.mat >= 0)
    cv.tone[wall_px] = np.clip(cv.tone[wall_px], 0, 3)
    df = inner_dist(frame)
    fh = np.clip(df / 1.2, 0, 1)
    cv.shade(frame, lit(np.where(frame, fh, 0) + np.where(inside, -0.4, 0), 2.6), "stone_d", bias=-0.08)
    cv.tone[frame] = np.clip(cv.tone[frame], 0, 4)
    # niche interior: deep shadow, brighter toward the bottom-left
    depth = np.clip((Y - apex) / (sill - apex), 0, 1)
    ni = 0.12 + 0.18 * depth - 0.05 * (X - cx) / half
    hood = inside & (Y < spring + 2)
    ang = np.arctan2(Y - (spring + 2), X - cx)
    rib = np.cos(ang * 9.0) > 0.35
    ni = np.where(hood & rib, ni + 0.22, ni)
    cv.shade(inside, ni, "stone_d")
    cv.hline(int(cx - half), int(cx + half), int(spring + 2), "stone_d", 1)
    # statue
    st = _statue()
    cv.paste(st, int(cx) - 12, 12)
    # sill
    cv.hline(int(cx - half - 3), int(cx + half + 3), int(sill), "stone_d", 3)
    cv.hline(int(cx - half - 3), int(cx + half + 3), int(sill) + 1, "stone_d", 2)
    cv.hline(int(cx - half - 2), int(cx + half + 2), int(sill) + 2, "stone_d", 1)
    cv.tidy()
    return cv


def _statue() -> Indexed:
    """A veiled, winged mourner in pale stone (24 x 34): head bowed under a
    veil, hands folded at the breast, robe in long folds, wings closed."""
    vc = vol(24, 34)
    vc.ellipsoid((5.5, 15), 4.0, 11.5, "ivory_d", rot_deg=-10, ambient=0.12, bias=-0.12, name="wing_l")
    vc.ellipsoid((18.5, 15), 4.0, 11.5, "ivory_d", rot_deg=10, ambient=0.12, bias=-0.18, name="wing_r")
    vc.cloth([(7, 11), (17, 11), (19.5, 31), (4.5, 31)], "ivory_d", folds=3.0, amp=0.5, fan=0.05,
             ambient=0.14, name="robe")
    vc.ellipsoid((12, 12.5), 5.0, 3.2, "ivory_d", ambient=0.16, name="shoulders")
    vc.ellipsoid((12, 7.5), 3.4, 4.0, "ivory_d", ambient=0.16, name="veil")
    vc.ellipsoid((12.6, 8.4), 2.2, 2.6, "ivory_d", ambient=0.2, bias=0.06, name="face")
    vc.ellipsoid((12, 15.8), 2.6, 2.0, "ivory_d", ambient=0.2, bias=0.08, name="hands")
    vc.capsule((4, 32.5), (20, 32.5), 1.5, 1.5, "stone", ambient=0.2, name="plinth")
    ix = resolve(vc)
    ix.set_px(12, 9, "ivory_d", 1)
    ix.set_px(13, 9, "ivory_d", 1)
    return ix


