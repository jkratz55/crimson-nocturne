FG_SIZE = (1024, 18 * T)        # covers every camera of a 48-cell room at scroll 1.3
FG_SCROLL = (1.3, 1.0)
FG_Z = 18                       # over actors (<= 10), fire (15); under sparks (20), damage numbers (30)
# Screen x = texel - 1.3 * camera x (texels past 384 are off-screen at the
# opening camera, x 0); vertically the plane moves with the world, so a
# texel's y is its world y. Over its visible camera range a silhouette
# slides 0.3 * camera across the world.
#
# Hanging lanterns: (texel x, lantern top y). Lantern A stays over world x
# 302-413 and ends at y 130, so it never overlaps a walkable surface (the
# row-8 ledges are elsewhere) or the head of a hero standing on the row-12
# ledges below it (crown y 144). Lantern B hangs high (it ends at y 64,
# above the hall portrait's pediment and the row-8 ledge heads at y 80), so
# it shows only in the upper views.
# (A full-height column front was tried and dropped: at any position it
# sweeps across a ledge and makes the walkable surface look broken.)
FG_LAMPS: tuple[tuple[int, int], ...] = ((404, 92), (744, 26))
# Bottom-edge silhouettes, (kind, texel x of the left edge): the tops of a
# near balustrade and an urn on its plinth that rise from the room's bottom
# edge (y 288) to y >= FG_TOP, i.e. only over the floor's fascia and the
# foundation, 10 px under the soles at the ground camera (screen y >= 194),
# so they never cross a body or a walkable surface. One every ~270 px on
# screen; the first two frame the hero at the opening camera.
FG_FLOOR = 18 * T               # the room's bottom edge
FG_TOP = 266                    # nothing on the bottom silhouettes rises above this
FG_SILLS: tuple[tuple[str, int], ...] = (("balustrade", 60), ("urn", 330), ("balustrade_r", 598))
FG_RIM = 0                      # tone index of the single "fg_rim" colour
FG_LAMP_H = 39                  # lantern height, cap top to finial tip (its hanging ring sits 1 px above)


def _fg_lamp(cv: Canvas, cx: int, lamp_top: int) -> None:
    """A chain hanging from the vault with a pierced iron lantern on it,
    seen very close (15 px at the cap, 39 px tall): near-black iron with
    dark navy glass panes behind two lattice bars, a 2x2 dull moonlit
    highlight on the glass, and a 1-px cool moon rim down the right edge
    and along the cap. Unlit: every flame on screen stays a breakable
    candle."""
    cap0 = lamp_top
    body0, body1 = lamp_top + 8, lamp_top + 29
    ring = body1 + 1
    for y in range(0, cap0 - 1):                               # chain: face-on and edge-on links
        k = y % 4
        if k == 1:
            cv.px(cx - 1, y, "iron", 1)
            cv.px(cx + 1, y, "iron", 2)
        else:
            cv.px(cx, y, "iron", 2 if k == 3 else (1 if k == 0 else 0))
    cv.hline(cx - 1, cx + 1, cap0 - 1, "iron", 1)               # the hanging ring
    # pointed cap with a finial knob and a flared rim
    for k, half in enumerate((0, 1, 2, 3, 4, 5, 6, 7)):
        cv.hline(cx - half, cx + half, cap0 + k, "iron", 0 if k < 6 else 1)
    cv.px(cx, cap0, "iron", 1)
    # body: iron frame (corner posts + a middle bar), glass panes between
    for y in range(body0, body1 + 1):
        cv.hline(cx - 6, cx + 6, y, "iron", 0)
        if body0 + 1 <= y <= body1 - 1:
            cv.hline(cx - 5, cx - 1, y, "glass", 0)
            cv.hline(cx + 1, cx + 5, y, "glass", 1 if y < body0 + 10 else 0)
        cv.px(cx - 6, y, "iron", 1)
    for gx in (cx - 3, cx + 3):                                # thin lattice bars over the glass
        cv.vline(gx, body0 + 1, body1 - 1, "iron", 0)
    for y in (body0 + 7, body0 + 14):
        cv.hline(cx - 5, cx + 5, y, "iron", 0)
    cv.rect(cx + 1, body0 + 2, cx + 2, body0 + 3, "glass", 2)  # 2x2 dull moonlit highlight
    cv.hline(cx - 7, cx + 7, ring, "iron", 1)                  # drip ring
    for k, half in enumerate((5, 4, 3, 2, 1, 1, 0, 0)):
        cv.hline(cx - half, cx + half, ring + 1 + k, "iron", 0)  # finial
    for y in range(cap0, ring + 9):                             # moon rim: the right edge of every row
        row = np.nonzero(cv.mat[y, cx - 8:cx + 9] >= 0)[0]
        if len(row):
            cv.px(cx - 8 + int(row[-1]), y, "fg_rim", FG_RIM)
    for k in range(1, 6):                                       # ...and the cap's moonward slope
        cv.px(cx + k, cap0 + k, "fg_rim", FG_RIM)


BALUSTER = (3, 2, 1, 1, 2, 3, 3, 3, 2, 1, 2, 3, 3)   # vase baluster half-widths, abacus down to the foot


def _span_mask(spans: Sequence[tuple[int, int, int]], w: int, h: int) -> Mask:
    """Boolean mask from (row, x0, x1) inclusive spans."""
    m = np.zeros((h, w), bool)
    for y, a, b in spans:
        if 0 <= y < h:
            m[y, max(0, a):min(w, b + 1)] = True
    return m


def _fg_newel_spans(x0: int, w: int) -> list[tuple[int, int, int]]:
    """A square newel post 22 px tall: a moulded cap (rows 0-2), a fillet
    row and the shaft down to the bottom edge."""
    x1 = x0 + w - 1
    return [(y, x0, x1) for y in range(3)] + [(y, x0 + 1, x1 - 1) for y in range(3, 22)]


def _fg_rail_spans(x0: int, x1: int) -> list[tuple[int, int, int]]:
    """A handrail (rows 4-8) with vase balusters under it every 9 px."""
    spans = [(y, x0, x1) for y in range(4, 8)] + [(8, x0 + 1, x1 - 1)]
    for bx in range(x0 + 5, x1 - 3, 9):
        for k, half in enumerate(BALUSTER):
            spans.append((9 + k, bx - half, bx + half))
    return spans


# A campana urn on its plinth, row by row from the lid's knob down to the
# foot: half-widths of the body (rows 0-18); the plinth's cornice and die
# follow in rows 19-21. Knob, lid dome, a flared lip, an inverted-bell
# bowl, a short stem and a foot.
URN_HALVES = (1, 2, 1, 5, 7, 10, 10, 8, 8, 8, 7, 7, 6, 5, 4, 2, 2, 4, 5)
# One looped handle on each side of the bowl's shoulder, as (row, x0, x1)
# offsets from the urn's centre column for the right handle (mirrored for
# the left one): attached at rows 8 and 11, open in between.
URN_HANDLE = ((8, 8, 9), (9, 10, 10), (10, 10, 10), (11, 7, 9))


def _fg_urn_spans(x0: int) -> list[tuple[int, int, int]]:
    """An urn on its plinth (34 px wide, 22 tall): `URN_HALVES` with the
    two `URN_HANDLE` loops, on a corniced plinth top (the cornice overhangs
    the die by 1 px each side)."""
    cx = x0 + 16
    spans = [(k, cx - hh, cx + hh - 1) for k, hh in enumerate(URN_HALVES)]
    for y, a, b in URN_HANDLE:
        spans += [(y, cx + a, cx + b), (y, cx - 1 - b, cx - 1 - a)]
    spans += [(19, x0 - 1, x0 + 32), (20, x0, x0 + 31)]
    spans += [(y, x0 + 1, x0 + 30) for y in range(21, 22)]
    return spans


def _fg_sill(cv: Canvas, kind: str, x0: int) -> None:
    """One bottom-edge silhouette (rows 0..21 = texture y FG_TOP..287),
    drawn from row spans relative to its left edge `x0`: an S0 body, S1 on
    the faces that look up into the hall, 1-px G1 fillets, and the cool
    moon rim down every right (moonward) contour and along the tops of the
    caps, rails, lid and lip only, so a vase baluster or the urn's bowl
    reads as one clean profile line instead of a stepped zigzag."""
    h = FG_FLOOR - FG_TOP
    spans: list[tuple[int, int, int]] = []
    faces: list[tuple[int, int, int]] = []
    gold: list[tuple[int, int, int]] = []
    tops: tuple[int, ...]                           # rows whose upward-facing edges take the rim
    if kind in ("balustrade", "balustrade_r"):
        if kind == "balustrade":                    # 56 px: newel, 3 balusters, newel
            posts, rail = (0, 46), (10, 45)
        else:                                       # 48 px: a rail running in from the left, newel
            posts, rail = (38,), (0, 37)
        for px0 in posts:
            spans += _fg_newel_spans(px0, 10)
            faces += [(1, px0, px0 + 9), (2, px0, px0 + 9)]
            gold.append((3, px0 + 1, px0 + 8))
        spans += _fg_rail_spans(*rail)
        faces += [(5, rail[0], rail[1]), (6, rail[0], rail[1])]
        gold.append((7, rail[0], rail[1]))
        tops = (0, 4)
    elif kind == "urn":
        spans = _fg_urn_spans(0)
        faces += [(3, 0, 33), (4, 0, 33), (5, 0, 33), (19, -1, 32)]
        gold += [(6, 9, 24), (20, 0, 31)]
        tops = (0, 1, 3, 4, 5, 8, 17, 19)
    else:
        raise ValueError(f"unknown foreground silhouette {kind!r}")
    pad, w = 1, 66                                  # 1 px margin for the urn's overhanging cornice

    def mask(sp: list[tuple[int, int, int]]) -> Mask:
        return _span_mask([(y, a + pad, b + pad) for y, a, b in sp], w, h)

    m = mask(spans)
    up = np.zeros_like(m)
    up[1:] = m[:-1]
    right = np.zeros_like(m)
    right[:, :-1] = m[:, 1:]
    top_rows = np.zeros_like(m)
    top_rows[list(tops), :] = True
    sub = Canvas(w, h)
    sub.fill(m, "stone", 0)
    sub.fill(mask(faces) & m, "stone", 1)
    sub.fill(mask(gold) & m, "gold", 1)
    sub.fill(m & (~right | (~up & top_rows)), "fg_rim", FG_RIM)
    cv.paste(sub, x0 - pad, FG_TOP)


def foreground() -> Image.Image:
    """The foreground plane (docs/art_style.md): sparse, near-black silhouettes that pass in
    front of the action faster than the playfield (scroll 1.3), each with
    a 1-px cool moon rim: two chain-hung lanterns high up, and the tops of
    a near balustrade and an urn rising from the bottom edge over the
    foundation. Nothing ever crosses a walkable surface, a body, or the
    head height of a hero standing on a ledge."""
    cv = Canvas(*FG_SIZE)
    for x, top in FG_LAMPS:
        _fg_lamp(cv, x, top)
    for kind, x in FG_SILLS:
        _fg_sill(cv, kind, x)
    lamp_bottom = max(top + FG_LAMP_H - 1 for _, top in FG_LAMPS)
    if lamp_bottom > 135 or (cv.mat[lamp_bottom + 1:FG_TOP] >= 0).any():
        raise ValueError("a foreground silhouette reaches into the play area")
    return cv.image()


def build_tileset() -> None:
    ab = build_atlas()
    foreground().save(FOREGROUND_PNG)
    ab.foreground = {"texture": "res://assets/tiles/castle_foreground.png", "scroll_scale": list(FG_SCROLL),
                     "z_index": FG_Z}
    ab.save()


def build() -> None:
    build_tileset()


if __name__ == "__main__":
    build()
