FIELD_W, FIELD_H = 8, 4          # wall field size in cells (128 x 64 px)


def wall_field(bias: float = -0.04, mat: str = "stone", cap: int | None = None) -> Canvas:
    """The world-periodic wall: picked by (x mod 8, y mod 4), so every wall
    of any shape is seamless. The ceiling variant uses the same blocks in
    `stone_d` with a negative `bias` and its tones capped (`cap`), so the
    top of the room sits in the vignette (docs/art_style.md) and the gold cornice is
    the line that frames it."""
    cv, _, _ = masonry(FIELD_W * T, FIELD_H * T, seed=101, mat=mat, widths=(16, 24, 32, 32, 40, 48),
                       split_p=0.22, rough_p=0.22, crack_p=0.12, bias=bias)
    if cap is not None:
        cv.tone = np.minimum(cv.tone, cap).astype(np.int16)
    return cv


EDGE_TOP, EDGE_RIGHT, EDGE_BOTTOM, EDGE_LEFT = 1, 2, 4, 8


def edge_overlay(mask: int) -> Canvas:
    """Exposure overlay for a solid wall cell (drawn on the TileEdges layer
    over the world-periodic field): a lit lip where the top is open, an
    underside shadow below, a lit arris on open left sides and a shadowed
    one on open right sides (the light comes from the top-left)."""
    cv = Canvas(T, T)
    if mask & EDGE_LEFT:
        cv.vline(0, 0, T - 1, "stone", 5)
        cv.vline(1, 1, T - 2, "stone", 4)
    if mask & EDGE_TOP:
        cv.hline(0, T - 1, 0, "stone", 6)
        cv.hline(0, T - 1, 1, "stone", 5)
    if mask & EDGE_RIGHT:
        cv.vline(T - 1, 0, T - 1, "stone", 1)
        cv.vline(T - 2, 1 if mask & EDGE_TOP else 0, T - 1, "stone", 2)
    if mask & EDGE_BOTTOM:
        cv.hline(0, T - 1, T - 1, "stone", 0)
        cv.hline(0, T - 1, T - 2, "stone", 1)
        if mask & EDGE_LEFT:
            cv.px(0, T - 2, "stone", 4)
    if mask & EDGE_TOP and mask & EDGE_RIGHT:
        cv.px(T - 1, 0, "stone", 4)
    return cv


def _vein(cv: Canvas, rng: random.Random, x0: float, y0: float, length: int, mat: str, tone: int,
          slope: float, clip: tuple[int, int, int, int]) -> None:
    """A thin wandering marble vein."""
    cx0, cy0, cx1, cy1 = clip
    x, y = x0, y0
    ang = math.atan(slope)
    for _ in range(length):
        xi, yi = int(round(x)), int(round(y))
        if cx0 <= xi <= cx1 and cy0 <= yi <= cy1:
            cv.px(xi, yi, mat, tone)
        ang += rng.uniform(-0.5, 0.5)
        ang = max(-1.2, min(1.2, ang))
        x += math.cos(ang)
        y += math.sin(ang) * 0.8


def _fascia(cv: Canvas, rng: random.Random) -> None:
    """Front face of a floor slab, rows 7..15: polished wine marble with a
    dark-gold inlay fillet and a pale vein. Kept quiet: the inlay is G1
    with a G2 stud every 8 px, so the floor never stacks bright full-width
    lines under the run line."""
    cv.hline(0, T - 1, 7, "wine", 3)
    for y in range(8, 15):
        cv.hline(0, T - 1, y, "wine", 2 if y < 12 else 1)
    cv.hline(0, T - 1, 10, "gold", 1)
    for x in range(0, T, 8):
        cv.px(x + 3, 10, "gold", 2)
    _vein(cv, rng, rng.uniform(0, 8), rng.uniform(12, 13.5), 14, "wine", 3, rng.uniform(-0.3, 0.3),
          (0, 11, T - 1, 14))
    cv.hline(0, T - 1, 15, "wine", 0)


# Marble floor-top variants, keyed by seed % 4: (sheen dashes, wear specks),
# so neighbouring tiles differ visibly instead of only in dash positions.
_FLOOR_VARIANTS: dict[int, tuple[int, int]] = {0: (2, 1), 1: (3, 2), 2: (1, 3), 3: (4, 0)}


def floor_top(kind: str, seed: int) -> Canvas:
    """Walkable floor surface (top row y=0 is the floor line).

    - rows 0..5: the top surface in slight perspective: polished ivory
      marble with sheen dashes, or the crimson runner with gold borders and
      a 4 px lozenge motif (`kind` "carpet", "carpet_l", "carpet_r").
    - row 4/5: the nosing lip, row 6: shadow under the nosing.
    - rows 7..15: the slab's wine-marble fascia with a gold inlay line.

    Values sit one step under the old pass: the surface is M3 and the lip
    M4 (Y 156 / 193), so the floor reads as walkable without becoming the
    brightest line on a ground-floor screen. Variants differ in their
    sheen dashes and wear specks (see `_FLOOR_VARIANTS`)."""
    rng = random.Random(seed)
    cv = Canvas(T, T)
    cv.hline(0, T - 1, 0, "marble", 3)
    for y in (1, 2, 3):
        cv.hline(0, T - 1, y, "marble", 3)
    dashes, specks = _FLOOR_VARIANTS.get(seed % len(_FLOOR_VARIANTS), (3, 2))
    for _ in range(dashes):
        x = rng.randrange(0, T - 3)
        y = rng.choice((1, 2, 2))
        for k in range(rng.randint(2, 4)):
            cv.px(x + k, y, "marble", 4)
    for _ in range(specks):
        x = rng.randrange(0, T - 2)
        cv.px(x, 3, "marble", 2)
        cv.px(x + 1, 3, "marble", 2)
    cv.hline(0, T - 1, 4, "marble", 4)
    cv.hline(0, T - 1, 5, "marble", 2)
    cv.hline(0, T - 1, 6, "wine", 0)
    if kind.startswith("carpet"):
        x0, x1 = 0, T - 1
        if kind == "carpet_l":
            x0 = 5
        if kind == "carpet_r":
            x1 = T - 6
        for x in range(x0, x1 + 1):
            ph = x % 8
            cv.px(x, 0, "gold", 2)
            cv.px(x, 1, "crimson", 4 if ph in (3, 4) else 3)
            cv.px(x, 2, "gold", 3) if ph in (3, 4) else cv.px(x, 2, "crimson", 5 if ph in (2, 5) else 3)
            cv.px(x, 3, "crimson", 4 if ph in (3, 4) else 2)
            # a 1-px G3 border, a G4 glint only over each lozenge
            cv.px(x, 4, "gold", 4 if ph == 3 else 3)
            cv.px(x, 5, "crimson", 1)
        # end fringe: gold tassel threads over the nosing
        ex = x0 if kind == "carpet_l" else (x1 if kind == "carpet_r" else None)
        if ex is not None:
            for y in range(0, 6):
                cv.px(ex, y, "gold", 3 if y in (0, 4) else 2)
            step = -1 if kind == "carpet_l" else 1
            for k, ln in ((0, 3), (2 * step, 2)):
                for y in range(5, 5 + ln):
                    cv.px(ex + k + step, y, "gold", 3 if y == 5 else 2)
        for x in range(x0, x1 + 1, 4):
            if x not in (x0, x1):
                cv.px(x, 6, "gold", 1)
    _fascia(cv, rng)
    return cv


def slab_end(side: str, seed: int) -> Canvas:
    """Free end of a marble floor slab (balcony overhang): the top surface
    and fascia return around the end, and the underside is a dark moulding
    (the cell stays fully solid)."""
    cv = floor_top("marble", seed)
    for y in range(12, 16):
        cv.hline(0, T - 1, y, "wine", (2, 1, 1, 0)[y - 12])
    cv.hline(0, T - 1, 11, "wine", 2)
    if side == "r":
        cv.vline(T - 1, 1, 14, "wine", 0)
        cv.vline(T - 2, 1, 5, "marble", 2)
        cv.px(T - 1, 0, "marble", 2)
    else:
        cv.vline(0, 1, 14, "marble", 3)
        cv.px(0, 0, "marble", 4)
    return cv


PLINTH_WIDTHS = (1, 2, 3)        # foundation slab widths (cells)
PLINTH_VARIANTS = 3              # art variants per width; variant 0 carries the sheen


def plinth(cells: int, seed: int, sheen: bool) -> Canvas:
    """Foundation course under the walkable floor row: one slab of
    wine-black polished marble, `cells` x 16 px. It is the bottom band of
    every ground-floor screen, so it is deliberately the quietest, darkest
    collision art in the room (mean Y about 21, no ivory, no per-tile grid):

    - row 0: wine 1 under the fascia's dark bottom edge;
    - rows 1-11: wine 1 clouded with wine 2 (at most ~30 % of the area, in
      horizontally drawn-out clusters of 3 px or more);
    - an optional 1-px diagonal wine-3 sheen streak (`sheen`);
    - the slab joint on the left edge: a 1-px wine-0 groove with a 1-px lit
      arris to its right (the builder lays 16/32/48 px slabs by hash, so the
      joints never fall on a regular grid);
    - rows 12-15: the bottom vignette, down to wine 0 and then the void."""
    rng = random.Random(seed)
    w = cells * T
    cv = Canvas(w, T)
    face = np.zeros((T, w), bool)
    face[1:12, :] = True
    # clouds drawn out along the slab: sample a twice-as-tall noise field
    # on every other row
    cloud = fbm(w, 2 * T, 3, 8, seed=seed, tileable=False)[::2]
    thr = float(np.quantile(cloud[face], 0.72))
    cv.fill(face, "wine", 1)
    cv.fill(face & (cloud > thr), "wine", 2)
    cv.hline(0, w - 1, 0, "wine", 1)
    cv.tidy()
    if sheen:
        n = rng.randint(4, 6)
        x0 = rng.randint(4, max(5, w - n - 4))
        y0 = rng.randint(2, 11 - n)
        for k in range(n):
            cv.px(x0 + k, y0 + k, "wine", 3)
    # slab joint at the left edge: groove + lit arris (top rows brightest)
    cv.vline(0, 0, 13, "wine", 0)
    cv.vline(1, 1, 3, "wine", 3)
    cv.vline(1, 4, 11, "wine", 2)
    # bottom vignette
    cv.hline(0, w - 1, 12, "wine", 1)
    cv.hline(0, w - 1, 13, "wine", 0)
    cv.hline(0, w - 1, 14, "void", 0)
    cv.hline(0, w - 1, 15, "void", 0)
    return cv


def cornice(seed: int) -> Canvas:
    """Ceiling trim (collision row under the ceiling): fascia, gold
    bead-and-reel, a lit cyma, a dentil course and the dark soffit."""
    rng = random.Random(seed)
    cv = Canvas(T, T)
    cv.hline(0, T - 1, 0, "stone", 1)
    cv.hline(0, T - 1, 1, "stone", 3)
    cv.hline(0, T - 1, 2, "stone", 2)
    for x in range(T):
        bead = x % 3 != 2
        # G4 glint on every other bead only: the cornice frames the room
        # without becoming a row of sparks under the HUD
        cv.px(x, 3, "gold", 4 if bead and x % 6 == 0 else (3 if bead else 1))
        cv.px(x, 4, "gold", 2 if bead else 0)
    cv.hline(0, T - 1, 5, "stone", 1)
    for y, tn in ((6, 6), (7, 5), (8, 4), (9, 3)):
        cv.hline(0, T - 1, y, "stone", tn)
    for _ in range(2):
        x = rng.randrange(T)
        cv.px(x, 8, "stone", 3)
    cv.hline(0, T - 1, 10, "stone", 1)
    for x in range(T):
        tooth = x % 4 in (0, 1)
        cv.px(x, 11, "stone", (5 if x % 4 == 0 else 4) if tooth else 0)
        cv.px(x, 12, "stone", 3 if tooth else 0)
    cv.hline(0, T - 1, 13, "stone", 2)
    cv.hline(0, T - 1, 14, "stone", 3)
    cv.hline(0, T - 1, 15, "stone", 0)
    return cv


def _corbel(cv: Canvas, cx: float, top: int, w: float, depth: int, mat: str = "stone",
            scroll: bool = True) -> None:
    """A carved scroll bracket hanging under a slab: a chamfered block that
    tapers into a curled volute."""
    h, wd = cv.h, cv.w
    X, Y = grid(wd, h)
    yb = top + depth
    half = np.where(Y < top + depth * 0.45, w / 2, w / 2 * (1 - (Y - (top + depth * 0.45)) / (depth * 0.75)))
    body = (Y >= top) & (Y < yb) & (np.abs(X - cx) < np.maximum(half, 0.6))
    d = inner_dist(body)
    hgt = np.clip(d / 1.6, 0, 1)
    if scroll:
        vy = top + depth * 0.62
        rr = np.hypot(X - (cx + w * 0.12), Y - vy)
        curl = body & (rr < w * 0.36)
        hgt = np.where(curl, hgt * 0.55 + 0.45 * np.clip(1.0 - rr / (w * 0.36), 0, 1), hgt)
    inten = lit(hgt, 2.4)
    cv.shade(body, inten, mat, bias=-0.04)
    if scroll:
        cv.px(int(cx + w * 0.12), int(top + depth * 0.62), mat, 0)


def ledge(kind: str, seed: int) -> Canvas:
    """One-way ledge (collision: top 5 px). A marble slab with a lit lip,
    a gilded fillet and a shadowed underside, carried on carved stone
    corbels. `kind`: "l"/"r" free ends with a console and pendant, "m"
    middle with a corbel, "p" plain middle, "el"/"er" an end that butts
    against a pier: the lip turns down over a dark end joint, so the
    walkable surface visibly stops at the collision edge.

    The lip is M4 (Y 193), not near-white: walkable tops stay readable
    against the dark wall without out-shining the hero or the moon."""
    rng = random.Random(seed)
    cv = Canvas(T, T)
    cv.hline(0, T - 1, 0, "marble", 4)
    cv.hline(0, T - 1, 1, "marble", 3)
    cv.hline(0, T - 1, 2, "marble", 2)
    for _ in range(2):
        x = rng.randrange(1, T - 3)
        cv.px(x, 2, "marble", 1)
        cv.px(x + 1, 2, "marble", 1)
    for x in range(T):
        cv.px(x, 3, "gold", 4 if x % 4 == 1 else 3)
    cv.hline(0, T - 1, 4, "wine", 1)
    if kind in ("el", "er"):
        # butt end against a pier: a dark joint column at the collision
        # edge, the lip and fillet turning down beside it, and a corbel
        ex = 0 if kind == "el" else T - 1
        inward = 1 if kind == "el" else -1
        cv.vline(ex, 0, 5, "wine", 0)
        lit_end = kind == "el"                      # the left end faces the light
        cv.vline(ex + inward, 0, 2, "marble", 3 if lit_end else 1)
        cv.px(ex + inward, 3, "gold", 3 if lit_end else 1)
        cv.px(ex + inward, 4, "wine", 0)
        _corbel(cv, 8.0 + inward * 1.0, 5, 7.0, 9)
    elif kind == "m":
        _corbel(cv, 8.0, 5, 7.0, 9)
    elif kind in ("l", "r"):
        cx = 9.0 if kind == "l" else 7.0
        _corbel(cv, cx, 5, 9.0, 10)
        ex = 0 if kind == "l" else T - 1
        inward = 1 if kind == "l" else -1
        # rounded slab end
        cv.mat[0, ex] = -1
        cv.px(ex, 1, "marble", 4 if kind == "l" else 2)
        cv.px(ex, 2, "marble", 3 if kind == "l" else 1)
        cv.px(ex, 3, "gold", 3 if kind == "l" else 2)
        cv.px(ex, 4, "wine", 0)
        cv.px(ex + inward, 0, "marble", 4)
        # pendant drop under the end
        px0 = ex + inward * 2
        for y, tn in ((5, 3), (6, 4), (7, 3), (8, 2)):
            cv.px(px0, y, "gold", tn)
            cv.px(px0 + inward, y, "gold", tn - 1)
        cv.px(px0, 9, "gold", 4)
    return cv


