# ==========================================================================
# 1x material canvas
# ==========================================================================
class Canvas:
    """A 1x image as material + ramp tone per pixel (-1 = transparent).

    Shapes are lit and quantized into their own ramp, so a pixel can never
    take an off-material colour; outlines and accents are drawn afterwards
    as exact tones."""

    def __init__(self, w: int, h: int) -> None:
        self.w, self.h = w, h
        self.mat = np.full((h, w), -1, np.int16)
        self.tone = np.zeros((h, w), np.int16)
        self.mats: list[str] = []

    def mid(self, name: str) -> int:
        if name not in TR:
            raise KeyError(f"unknown tile material {name!r}")
        if name not in self.mats:
            self.mats.append(name)
        return self.mats.index(name)

    def _clamp(self, name: str, tone: np.ndarray | int) -> np.ndarray | int:
        n = len(TR[name])
        return np.clip(tone, 0, n - 1)

    # -- writes ------------------------------------------------------------
    def fill(self, mask: Mask, mat: str, tone: np.ndarray | int) -> Canvas:
        m = np.asarray(mask, bool)
        self.mat[m] = self.mid(mat)
        t = np.broadcast_to(np.asarray(self._clamp(mat, tone), np.int16), m.shape)
        self.tone[m] = t[m]
        return self

    def shade(self, mask: Mask, inten: np.ndarray, mat: str, *, bias: float = 0.0,
              th: Sequence[float] | None = None) -> Canvas:
        """Quantize `inten` into `mat`'s ramp wherever `mask` is set."""
        cuts = th if th is not None else TH.get(mat)
        n = len(TR[mat])
        if cuts is not None and len(cuts) != n - 1:
            cuts = None
        idx = quantize_to_ramp(np.asarray(inten, np.float64) + bias, n, thresholds=cuts)
        return self.fill(mask, mat, idx)

    def px(self, x: int, y: int, mat: str, tone: int) -> Canvas:
        if 0 <= x < self.w and 0 <= y < self.h:
            self.mat[y, x] = self.mid(mat)
            self.tone[y, x] = int(self._clamp(mat, tone))
        return self

    def hline(self, x0: int, x1: int, y: int, mat: str, tone: int) -> Canvas:
        for x in range(x0, x1 + 1):
            self.px(x, y, mat, tone)
        return self

    def vline(self, x: int, y0: int, y1: int, mat: str, tone: int) -> Canvas:
        for y in range(y0, y1 + 1):
            self.px(x, y, mat, tone)
        return self

    def rect(self, x0: int, y0: int, x1: int, y1: int, mat: str, tone: int) -> Canvas:
        for y in range(y0, y1 + 1):
            self.hline(x0, x1, y, mat, tone)
        return self

    def line(self, pts: Sequence[tuple[float, float]], mat: str, tone: int | Callable[[float], int]) -> Canvas:
        pix = _polyline_pixels(pts)
        n = max(1, len(pix) - 1)
        for k, (x, y) in enumerate(pix):
            t = tone(k / n) if callable(tone) else tone
            self.px(x, y, mat, t)
        return self

    def clear(self, mask: Mask) -> Canvas:
        self.mat[np.asarray(mask, bool)] = -1
        return self

    def shift_tone(self, mask: Mask, delta: int) -> Canvas:
        m = np.asarray(mask, bool) & (self.mat >= 0)
        for mi, name in enumerate(self.mats):
            sel = m & (self.mat == mi)
            self.tone[sel] = np.clip(self.tone[sel] + delta, 0, len(TR[name]) - 1)
        return self

    def paste(self, other: Canvas | Indexed, dx: int = 0, dy: int = 0) -> Canvas:
        """Copy another canvas's opaque pixels in front of this one."""
        names = other.mats
        ys, xs = np.nonzero(other.mat >= 0)
        for y, x in zip(ys.tolist(), xs.tolist()):
            self.px(x + dx, y + dy, names[int(other.mat[y, x])], int(other.tone[y, x]))
        return self

    # -- queries / cleanup -------------------------------------------------
    def is_mat(self, name: str) -> Mask:
        if name not in self.mats:
            return np.zeros((self.h, self.w), bool)
        return self.mat == self.mats.index(name)

    def tidy(self, keep: Mask | None = None) -> Canvas:
        """Remove single-pixel tone orphans (clusters of at least 2 px)."""
        self.tone = remove_orphans(self.tone, np.where(self.mat >= 0, self.mat, -1), min_same=3,
                                   keep=keep).astype(np.int16)
        return self

    def image(self) -> Image.Image:
        out = np.zeros((self.h, self.w, 4), np.uint8)
        for mi, name in enumerate(self.mats):
            sel = self.mat == mi
            if sel.any():
                lut = ramp_array(TR[name])
                out[sel, :3] = lut[np.clip(self.tone[sel], 0, len(lut) - 1)]
                out[sel, 3] = 255
        return Image.fromarray(out, "RGBA")


def _polyline_pixels(pts: Sequence[tuple[float, float]]) -> list[tuple[int, int]]:
    ip = [(int(round(x)), int(round(y))) for x, y in pts]
    out: list[tuple[int, int]] = []
    for i in range(len(ip) - 1):
        x0, y0 = ip[i]
        x1, y1 = ip[i + 1]
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        seg: list[tuple[int, int]] = []
        while True:
            seg.append((x0, y0))
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy
        out.extend(seg if not out else seg[1:])
    if len(ip) == 1:
        out = list(ip)
    return out


