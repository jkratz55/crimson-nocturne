def _course_blocks(rng: random.Random, w: int, widths: Sequence[int], prev: list[int],
                   wrap: bool, min_gap: int = 5) -> tuple[int, list[int]]:
    """Pick block widths for one course: returns (start x, widths). Joints
    keep at least `min_gap` px from the joints of the course above."""
    best: tuple[int, list[int]] | None = None
    for _ in range(120):
        x0 = rng.randrange(w) if wrap else -rng.randrange(0, max(widths))
        ws: list[int] = []
        span = w if wrap else w - x0
        while sum(ws) < span:
            ws.append(rng.choice(widths))
        if wrap:
            ws[-1] -= sum(ws) - w
            if ws[-1] < min(widths) - 4 and len(ws) > 1:
                ws[-2] += ws.pop()
        joints = [(x0 + sum(ws[:i])) % w if wrap else x0 + sum(ws[:i]) for i in range(len(ws))]

        def gap(j: int, p: int) -> int:
            d = abs(j - p)
            return min(d, w - d) if wrap else d

        if all(gap(j, p) >= min_gap for j in joints for p in prev):
            return x0, ws
        best = (x0, ws)
    assert best is not None
    return best


def masonry_ids(w: int, h: int, seed: int, *, courses: Sequence[int] | None = None,
                widths: Sequence[int] = (16, 24, 32, 32, 40, 48), split_p: float = 0.2,
                wrap: bool = True) -> tuple[np.ndarray, int]:
    """Block-id map of an ashlar wall: -1 marks the 1 px mortar on each
    block's top and left, so blocks of any size share one joint grid."""
    rng = random.Random(seed)
    if courses is None:
        courses = [16] * (h // 16) + ([h % 16] if h % 16 else [])
    bid = np.full((h, w), -1, np.int32)
    y = 0
    prev: list[int] = []
    k = 0
    for ch in courses:
        x0, ws = _course_blocks(rng, w, widths, prev, wrap)
        joints: list[int] = []
        xa = x0
        for bw in ws:
            joints.append(xa % w if wrap else xa)
            halves = [(y, y + ch // 2), (y + ch // 2, y + ch)] if ch >= 16 and rng.random() < split_p \
                else [(y, y + ch)]
            for a, b in halves:
                for yy in range(a + 1, min(b, h)):
                    for d in range(1, bw):
                        xx = xa + d
                        if wrap:
                            xx %= w
                        elif not 0 <= xx < w:
                            continue
                        bid[yy, xx] = k
                k += 1
            xa += bw
        prev = joints
        y += ch
    return bid, k


def masonry(w: int, h: int, seed: int, mat: str = "stone", *, courses: Sequence[int] | None = None,
            widths: Sequence[int] = (16, 24, 32, 32, 40, 48), split_p: float = 0.2, wrap: bool = True,
            region: Mask | None = None, bevel: float = 2.0, rough_p: float = 0.25,
            crack_p: float = 0.10, chip_p: float = 0.35, jitter: float = 0.06, grain: float = 0.11,
            bias: float = 0.0, strength: float = 2.2, extra_height: np.ndarray | None = None,
            light_bias: np.ndarray | None = None, mortar_tone: int = 0
            ) -> tuple[Canvas, np.ndarray, np.ndarray]:
    """Lit ashlar. Returns (canvas, block ids, height field).

    - Chamfered blocks (`bevel` px), some rusticated (`rough_p`) with a
      bulging, pitted face.
    - Per-block value jitter (±`jitter`) and clustered surface grain.
    - Chipped corners (`chip_p`) and hairline cracks (`crack_p`), carved
      into the height field so the light draws them.
    - `region` limits the wall to a mask; its boundary becomes mortar.
    - `light_bias` (h, w) adds a baked light pool (candle glow, vignette).
    """
    rng = np.random.default_rng(seed)
    prng = random.Random(seed * 31 + 7)
    bid, n = masonry_ids(w, h, seed, courses=courses, widths=widths, split_p=split_p, wrap=wrap)
    reg = np.ones((h, w), bool) if region is None else np.asarray(region, bool)
    solid = (bid >= 0) & reg
    d = inner_dist(solid, wrap=wrap and region is None)
    hgt = np.clip((d - 0.5) / bevel, 0.0, 1.0)
    rough = rng.random(max(n, 1)) < rough_p
    bump = fbm(w, h, 3, 5, seed=seed + 11, tileable=wrap)
    pill = np.clip(d / 5.0, 0, 1) ** 0.5
    rmask = solid & rough[np.maximum(bid, 0)]
    hgt = np.where(rmask, np.minimum(hgt, 0.75) + pill * 0.35 + (bump - 0.5) * 0.35, hgt)
    # chips and cracks, carved per block
    for b in range(n):
        ys, xs = np.nonzero(bid == b)
        if len(xs) < 12:
            continue
        if wrap and (xs.max() - xs.min()) > w // 2:  # block wraps around the seam
            xs = np.where(xs < w // 2, xs + w, xs)
        x0, x1, y0, y1 = int(xs.min()), int(xs.max()), int(ys.min()), int(ys.max())
        if prng.random() < chip_p:
            cx = x0 if prng.random() < 0.5 else x1
            cy = y0 if prng.random() < 0.6 else y1
            size = prng.choice((2, 2, 3))
            for oy in range(size):
                for ox in range(size - oy):
                    xx = cx + (ox if cx == x0 else -ox)
                    yy = cy + (oy if cy == y0 else -oy)
                    xx %= w
                    if 0 <= yy < h and bid[yy, xx] == b:
                        hgt[yy, xx] = 0.15
        if prng.random() < crack_p and (x1 - x0) >= 10:
            px_, py_ = float(prng.randint(x0 + 3, x1 - 3)), float(y0)
            ang = math.radians(prng.uniform(60, 120))
            for _ in range(prng.randint(5, 11)):
                ix_, iy_ = int(round(px_)) % w, int(round(py_))
                if 0 <= iy_ < h and bid[iy_, ix_] == b:
                    hgt[iy_, ix_] = min(hgt[iy_, ix_], 0.35)
                ang += math.radians(prng.uniform(-35, 35))
                px_ += math.cos(ang)
                py_ += abs(math.sin(ang)) + 0.3
    if extra_height is not None:
        hgt = hgt + extra_height
    hgt = np.where(solid, hgt, 0.0)
    inten = lit(hgt, strength, wrap=wrap and region is None)
    jit = rng.uniform(-jitter, jitter, max(n, 1))
    inten = inten + np.where(solid, jit[np.maximum(bid, 0)], 0.0)
    inten = inten + (fbm(w, h, 3, 4, seed=seed + 3, tileable=wrap) - 0.5) * grain * 2.0
    if light_bias is not None:
        inten = inten + light_bias
    cv = Canvas(w, h)
    cv.shade(solid, inten, mat, bias=bias)
    mortar = reg & ~solid
    cv.fill(mortar, mat, mortar_tone)
    cv.tidy()
    return cv, bid, hgt


