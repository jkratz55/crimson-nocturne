def grid(w: int, h: int) -> tuple[np.ndarray, np.ndarray]:
    X = np.arange(w, dtype=np.float64)[None, :] + 0.5
    Y = np.arange(h, dtype=np.float64)[:, None] + 0.5
    return np.broadcast_to(X, (h, w)), np.broadcast_to(Y, (h, w))


def rect_mask(w: int, h: int, x0: float, y0: float, x1: float, y1: float) -> Mask:
    """Inclusive pixel rectangle."""
    m = np.zeros((h, w), bool)
    m[max(0, int(y0)):max(0, int(y1) + 1), max(0, int(x0)):max(0, int(x1) + 1)] = True
    return m


def inner_dist(mask: Mask, wrap: bool = False) -> np.ndarray:
    """Distance (px) from each set pixel to the nearest unset one."""
    m = np.asarray(mask, bool)
    if wrap:
        h, w = m.shape
        return distance_transform_edt(np.tile(m, (3, 3)))[h:2 * h, w:2 * w]
    return distance_transform_edt(np.pad(m, 1))[1:-1, 1:-1]


def lit(hgt: np.ndarray, strength: float = 2.2, *, wrap: bool = False, ambient: float = 0.12,
        spec: float = 0.0, light: tuple[float, float, float] = LIGHT_ENV) -> np.ndarray:
    """Intensity in [0, 1] of a height field under the architecture light."""
    nx, ny, nz = heightmap_normals(hgt, strength, wrap)
    return shade_normals(nx, ny, nz, light, ambient=ambient, gamma=1.0, rim=0.0, spec=spec)


def vol(w: int, h: int, ss: int = 4) -> VolCanvas:
    """Volumetric canvas lit like the architecture (top-left key, no rim)."""
    return VolCanvas(w, h, ss, ramps=TR, light=LIGHT_ENV, rim=(0.0, 0.0, 0.0))


def resolve(vc: VolCanvas, **kw: object) -> Indexed:
    ix = vc.resolve(thresholds={k: v for k, v in TH.items() if k in vc.mats}, **kw)  # type: ignore[arg-type]
    return ix.remove_orphans(keep=())


