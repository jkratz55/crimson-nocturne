    plinth = rect_mask(w, h, 2, h - 4, w - 3, h - 1)
    hh = np.zeros((h, w))
    for m, lift in ((ped, 0.8), (cap, 1.1), (plinth, 1.1)):
        hh = np.where(m, np.maximum(hh, np.clip(inner_dist(m) / 1.5, 0, 1) * lift), hh)
