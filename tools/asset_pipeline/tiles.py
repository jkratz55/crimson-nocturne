def frieze(kind: str, seed: int) -> Canvas:
    """Band under the cornice (decor row): shadowed recessed frieze with a
    stone modillion ("a") or a gilt rosette ("b"), over a lit fillet."""
    rng = random.Random(seed)
    cv = Canvas(T, T)
    X, Y = grid(T, T)
    band = (Y < 13)
    hgt = np.where(Y < 1, 0.0, 0.6) + (fbm(T, T, 2, 4, seed=seed) - 0.5) * 0.25
    cv.shade(band, lit(hgt, 1.5) * 0.65, "stone_d")
    cv.hline(0, T - 1, 0, "stone_d", 0)
    cv.hline(0, T - 1, 1, "stone_d", 1)
    if kind == "a":
        body = (np.abs(X - 8) < 3.6) & (Y >= 1) & (Y < 12)
        d = inner_dist(body)
        hb = np.clip(d / 1.5, 0, 1) + np.where(Y > 8, -(Y - 8) * 0.12, 0)
        rr = np.hypot(X - 8.5, Y - 9.5)
        hb = np.where(rr < 2.2, hb * 0.6, hb)
        cv.shade(body, lit(np.where(body, hb, 0) + 0.0, 2.6), "stone")
        cv.px(8, 9, "stone", 1)
        cv.hline(5, 11, 12, "stone_d", 0)
    else:
        cx, cy = 8, 6
        for (dx, dy) in ((0, -2), (-2, 0), (2, 0), (0, 2)):
            cv.px(cx + dx, cy + dy, "gold", 3)
        for (dx, dy) in ((-1, -1), (1, -1), (-1, 1), (1, 1)):
            cv.px(cx + dx, cy + dy, "gold", 2)
        cv.px(cx, cy - 1, "gold", 4)
        cv.px(cx - 1, cy, "gold", 4)
        cv.px(cx, cy, "gold", 5)
        cv.px(cx + 1, cy, "gold", 2)
        cv.px(cx, cy + 1, "gold", 1)
        cv.px(cx + 1, cy + 2, "stone_d", 0)
        cv.px(cx + 2, cy + 1, "stone_d", 0)
    if rng.random() < 0.5:
        cv.px(rng.randrange(T), rng.randrange(3, 11), "stone_d", 1)
    cv.hline(0, T - 1, 13, "stone_d", 4)
    cv.hline(0, T - 1, 14, "stone_d", 3)
    cv.hline(0, T - 1, 15, "stone_d", 1)
    return cv


def pier_top(variant: str, seed: int) -> Canvas:
    """Pilaster rising from a pier capital to the frieze (2 x 4 cells):
    a projecting stone strip with a lit left arris, a shadowed right one and
    a recessed moulded panel. `variant` "mask" sets a moulded roundel in the
    panel with a carved horned grotesque whose eyes glint red."""
    w, h = 2 * T, 4 * T
    cv = Canvas(w, h)
    X, Y = grid(w, h)
    outer = np.ones((h, w), bool)
    panel = (X > 6) & (X < 26) & (Y > 5) & (Y < h - 4)
    d_out = inner_dist(outer)
    hgt = np.clip(d_out / 1.5, 0, 1) * 1.0
    d_in = inner_dist(~panel)
    hgt = np.where(panel, 0.45, np.minimum(hgt, 0.45 + np.clip(d_in / 1.6, 0, 1) * 0.55))
    hgt = hgt + (fbm(w, h, 3, 4, seed=seed) - 0.5) * 0.12
    inten = lit(hgt, 2.4)
    inten = inten - np.where(Y < 3, 0.25, 0.0)
    cv.shade(outer, inten, "stone_d")
    cv.hline(0, w - 1, 0, "stone_d", 0)
    cv.hline(0, w - 1, 1, "stone_d", 1)
    cv.vline(w - 1, 0, h - 1, "stone_d", 1)
    if variant == "mask":
        cx, cy, ro, ri = 16.0, 27.0, 10.5, 8.0
        rr = np.hypot(X - cx, Y - cy)
        ring = (rr < ro) & (rr >= ri)
        hollow = rr < ri
        rh = np.where(ring, 0.7 + 0.5 * np.sin((rr - ri) / (ro - ri) * math.pi), 0.0)
        rh = np.where(hollow, 0.2, rh)
        ri_ = lit(np.where(ring | hollow, rh, 0.45), 2.6)
        cv.shade(ring, ri_, "stone", bias=0.0)
        cv.shade(hollow, ri_ * 0.45, "stone_d")
        cv.paste(_mask_relief(seed), int(cx) - 9, int(cy) - 9)
        cv.paste(_sconce(seed), 8, 39)
    cv.tidy(keep=cv.is_mat("eye"))
    return cv


def _mask_relief(seed: int) -> Canvas:
    """A small carved grotesque (18 x 18): curled horns, a heavy brow over
    deep sockets with a red glint, a broad snout and a fanged open mouth."""
    vc = vol(18, 18)
    vc.capsule((5.0, 6.0), (1.6, 1.2), 1.5, 0.7, "stone", ambient=0.35, bias=0.12, group="horn_l",
               name="horn_l")
    vc.capsule((13.0, 6.0), (16.4, 1.2), 1.5, 0.7, "stone", ambient=0.35, bias=0.0, group="horn_r",
               name="horn_r")
    vc.ellipsoid((9, 10), 6.0, 7.0, "stone", ambient=0.32, bias=0.10, name="head")
    vc.ellipsoid((9, 7.2), 5.6, 2.0, "stone", ambient=0.35, bias=0.2, group="brow", name="brow")
    vc.ellipsoid((9, 11.2), 2.2, 2.3, "stone", ambient=0.35, bias=0.18, group="snout", name="snout")
    vc.ellipsoid((9, 14.6), 3.4, 1.5, "stone_d", ambient=0.0, bias=-0.7, name="mouth")
    ix = resolve(vc)
    ix.interior_contours(skip=(), tone=1)
    cv = Canvas(18, 18)
    cv.paste(ix)
    for x in (6, 11):
        cv.px(x, 9, "stone_d", 0)
        cv.px(x + (1 if x < 9 else -1), 9, "stone_d", 0)
    cv.px(6, 9, "eye", 1)
    cv.px(11, 9, "eye", 1)
    cv.px(7, 14, "stone", 5)
    cv.px(10, 14, "stone", 5)
    cv.px(9, 12, "stone", 1)
    return cv


def _sconce(seed: int) -> Canvas:
    """Two-branch wall sconce (16 x 22): an oval gilt backplate with an
    iron boss, two scrolled iron arms rising left and right to gilt drip
    pans, each holding a guttered, long-cold candle stub. The broad Y
    silhouette keeps it from reading as a blade."""
    cv = Canvas(16, 22)
    X, Y = grid(16, 22)
    plate = ((X - 8) / 3.0) ** 2 + ((Y - 15.5) / 5.0) ** 2 < 1.0
    cv.shade(plate, lit(np.clip(inner_dist(plate) / 1.4, 0, 1), 2.6), "gold", bias=-0.04)
    cv.px(8, 15, "iron", 3)
    cv.px(8, 16, "iron", 1)
    for y in range(12, 20):
        cv.px(11, y, "stone_d", 0)                   # cast edge on the wall
    cv.hline(7, 9, 21, "stone_d", 0)
    # arms: from the boss, out and up to the pans (lit side up-left)
    for (x, y, tn) in ((7, 16, 3), (6, 16, 3), (5, 15, 3), (4, 14, 3), (3, 13, 2), (3, 12, 2),
                       (9, 16, 2), (10, 16, 2), (11, 15, 2), (12, 14, 2), (13, 13, 1), (13, 12, 1),
                       (2, 13, 1), (14, 13, 1)):
        cv.px(x, y, "iron", tn)
    for cx in (3, 13):
        for x in range(cx - 3, cx + 4):
            cv.px(x, 10, "gold", 4 if x <= cx else 2)
            cv.px(x, 11, "gold", 2 if x <= cx else 1)
        # cold, guttered stubs one step down (no Y > 200 off-flame pixel)
        cv.rect(cx - 1, 6, cx + 1, 9, "wax", 1)
        cv.vline(cx - 1, 6, 9, "wax", 2)
        cv.vline(cx + 1, 7, 9, "wax", 0)
        cv.px(cx, 5, "wax", 2)
        cv.px(cx, 4, "iron", 1)
        cv.px(cx + 2, 10, "wax", 2)
        cv.px(cx + 2, 11, "wax", 1)
    return cv


CAP_MAT = "ivory_d"      # capital leaves: the statue marble (pale, desaturated), not gold
CAP_MAX = 4              # ...topping out at tone 4 (Y 123), under every walkable lip


def pier_cap(seed: int) -> Canvas:
    """Pier capital (2 cells wide): stone abacus whose profile continues
    into the arch imposts, and a carved stone bell with two tiers of
    acanthus leaves (each its own lit lobe, separated by dark contours, a
    midrib one tone down and a tip curling outward) and corner volutes.

    Gold is only an accent (about 25 px): a 1-px G3 line on the astragal
    with a G4 stud every 4 px, a G4 glint on the three upper leaf tips and
    one on the abacus fleuron. The leaves stay within S1-S5, so two or three
    capitals per screen read as stone carving, not as solid gold crowns."""
    w, h = 2 * T, T
    vc = vol(w, h)
    vc.polygon([(4, 3), (28, 3), (25, 14), (7, 14)], "stone_d", normal=(0.0, 0.0, 1.0), ambient=0.0,
               bias=-0.25, group="bell", name="bell")
    for k, cx in enumerate((10.0, 16.0, 22.0)):
        vc.ellipsoid((cx, 7.6), 3.1, 4.6, CAP_MAT, ambient=0.1, spec=0.25, bias=-0.1, group=f"up{k}",
                     name=f"up{k}")
    for k, cx in enumerate((4.6, 27.4)):
        vc.ellipsoid((cx, 5.6), 3.2, 2.7, CAP_MAT, ambient=0.12, spec=0.25, bias=-0.06, group=f"vol{k}",
                     name=f"vol{k}")
    for k, cx in enumerate((7.0, 13.0, 19.0, 25.0)):
        vc.ellipsoid((cx, 10.6), 3.0, 3.4, CAP_MAT, ambient=0.08, spec=0.25, group=f"lo{k}", name=f"lo{k}",
                     bias=-0.16)
    vc.capsule((7.0, 13.8), (25.0, 13.8), 1.2, 1.2, CAP_MAT, ambient=0.2, spec=0.2, group="astragal",
               name="astragal")
    ix = resolve(vc)
    ix.interior_contours(skip=(), tone=0)
    cv = Canvas(w, h)
    cv.paste(ix)
    leaf = cv.is_mat(CAP_MAT)
    cv.tone[leaf] = np.clip(cv.tone[leaf], 1, CAP_MAX)
    for cx in (10, 16, 22):          # upper-tier midribs and out-curled tips
        cv.vline(cx, 6, 9, CAP_MAT, 2)
        cv.px(cx - 1, 3, "gold", 4)
        cv.px(cx + 1, 3, CAP_MAT, 3)
    for cx in (7, 13, 19, 25):       # lower-tier midribs and tips
        cv.vline(cx, 10, 12, CAP_MAT, 2)
        cv.px(cx - 1, 7, CAP_MAT, 4)
    for cx, d in ((4, 1), (27, -1)):  # volute eyes
        cv.px(cx, 6, "stone_d", 0)
        cv.px(cx + d, 6, CAP_MAT, 1)
        cv.px(cx + d, 5, CAP_MAT, 4)
    # astragal: a single gilt line with studs
    for x in range(7, 26):
        cv.px(x, 13, "gold", 4 if x % 4 == 1 else 3)
    cv.hline(0, w - 1, 0, "stone", 4)
    cv.hline(0, w - 1, 1, "stone", 3)
    cv.hline(0, w - 1, 2, "stone", 1)
    cv.hline(14, 17, 1, "stone", 5)     # fleuron on the abacus
    cv.px(15, 0, "gold", 4)
    cv.px(16, 0, "stone", 5)
    cv.hline(6, w - 7, 15, "wine", 0)
    return cv


# The fluted shaft, drawn column by column (piece x 4..27, 24 px across)
# like a hand-placed cylinder ramp, light from the top-left. Five flutes
# with foreshortened fillets: the lit flank and the middle are wine 3 with
# wine-4 fillet catch-lights (the sheen), every groove is a single wine-2
# pixel, and the core shadow is a 5 px wine-1 / core band on the right with
# a 1-px reflected light before the outline. No wine-2 area is wider than
# 1 px: wine 2 (Y 35) is the value of the hero's dark contour, and he runs
# and jumps in front of every pier (the shaft's median is wine 3, Y 56).
SHAFT_X0 = 4
SHAFT_TONES: tuple[int, ...] = (0, 3, 4, 2, 3, 3, 4, 4, 4, 2, 3, 3, 3, 3, 3, 4, 3, 3, 1, 0, 0, 0, 1, 0)
# The 3-px core band (between the wine-1 terminator and reflected light) is
# drawn in `wine_core` (Y 18) rather than wine 0 (Y 10), so the hero's Y ~6
# contour separates from it when he jumps in front of a pier; the outline
# columns at either edge stay wine 0.
SHAFT_CORE: tuple[int, ...] = (19, 20, 21)


def _shaft_columns(cv: Canvas, y0: int, y1: int) -> None:
    for i, tn in enumerate(SHAFT_TONES):
        if i in SHAFT_CORE:
            cv.vline(SHAFT_X0 + i, y0, y1, "wine_core", 0)
        else:
            cv.vline(SHAFT_X0 + i, y0, y1, "wine", tn)


def pier_shaft(variant: str) -> Canvas:
    """Fluted, polished wine-marble column shaft (2 cells wide, 24 px
    across, see `SHAFT_TONES`). `variant` "ring" adds the dark-gold annulet
    that ledges hang from, level with the slab's fillet."""
    w = 2 * T
    cv = Canvas(w, T)
    _shaft_columns(cv, 0, T - 1)
    if variant == "ring":
        # a slim 2-px band (G1, a G2 catch-light on the lit left quarter)
        # under a wine-0 shadow row: it reads as a fitting on the column,
        # never as the ledge's walkable top running on past its collision
        cv.hline(3, w - 4, 1, "wine", 0)
        for x in range(3, w - 3):
            u = (x + 0.5 - 16.0) / 13.0
            cv.px(x, 2, "gold", 2 if -0.85 < u < -0.3 else (1 if u < 0.55 else 0))
            cv.px(x, 3, "gold", 1 if u < 0.2 else 0)
        cv.hline(4, w - 5, 4, "wine", 0)
    return cv


def _torus_row(cv: Canvas, y: int, x0: int, x1: int, part: str) -> None:
    """One row of a horizontal moulding drawn like the shaft: wine-3 face,
    the shaft's core pattern (its last six columns: terminator, core,
    reflected light, outline) on its right end, a wine-4 catch-light on the lit left 2/5 of
    its top row (`part` "top"), and a 1-px wine-0 crease for its shadowed
    underside (`part` "under")."""
    if part == "under":
        cv.hline(x0, x1, y, "wine", 0)
        return
    cv.hline(x0, x1, y, "wine", 3)
    if part == "top":
        cv.hline(x0 + 1, x0 + (x1 - x0) * 2 // 5, y, "wine", 4)
    for k, tn in enumerate(SHAFT_TONES[-6:]):
        cv.px(x1 - 5 + k, y, "wine", tn)


def pier_base(seed: int) -> Canvas:
    """Attic base in the shaft's own wine marble: two tori with a dark-gold
    fillet and a dark scotia, on a square plinth that stands on the floor
    line (2 x 2 cells).

    It stands in the quiet band behind the run line, so it is mid in value
    and low in contrast: every face is wine 3 (Y 56), the value the hero's
    dark sel-out contour separates from, and the rest is 1-px drawing.
    Each moulding has a short wine-4 catch-light on its lit left top edge,
    a 1-px wine-0 crease underneath and the shaft's core shadow on its
    right end. The plinth carries an incised panel (a wine-0 incision on
    its top and left, a lit lower lip, one broken vein), a lit wine-4
    chamfer down its left arris and a dark right arris, so it reads as the
    carved foot of the column and never as a lit step. Wine 2 (the hero's
    contour value) appears only as single pixels."""
    w, h = 2 * T, 2 * T
    cv = Canvas(w, h)
    _shaft_columns(cv, 0, 3)
    # dark-gold fillet under the shaft: G1, the lit third G2
    cv.hline(5, w - 6, 4, "gold", 1)
    cv.hline(6, 11, 4, "gold", 2)
    # upper torus (x 3..28)
    _torus_row(cv, 5, 4, w - 5, "top")
    for y in (6, 7, 8):
        _torus_row(cv, y, 3, w - 4, "face")
    _torus_row(cv, 9, 4, w - 5, "under")
    cv.hline(4, w - 5, 10, "wine", 0)               # scotia
    cv.hline(5, w - 6, 11, "gold", 1)               # fillet
    # lower torus (x 1..30)
    _torus_row(cv, 12, 2, w - 3, "top")
    for y in (13, 14, 15):
        _torus_row(cv, y, 1, w - 2, "face")
    _torus_row(cv, 16, 2, w - 3, "under")
    cv.hline(0, w - 1, 17, "wine", 0)               # joint onto the plinth
    # plinth (rows 18..31): wine-3 face; the lit left arris catches the
    # light (a wine-4 chamfer under the top catch-light), the right one is
    # in shadow
    cv.rect(0, 18, w - 2, h - 1, "wine", 3)
    cv.hline(2, w * 2 // 5, 18, "wine", 4)
    cv.vline(1, 18, h - 7, "wine", 4)
    cv.vline(w - 1, 18, h - 1, "wine", 0)
    cv.vline(w - 2, 19, h - 1, "wine", 1)
    cv.hline(1, w - 2, h - 1, "wine", 1)            # contact shadow on the floor
    # incised panel: the groove's upper and left walls in shadow (wine 0),
    # its lower wall catching the light (wine 4, lit left half only)
    px0, py0, px1, py1 = 4, 21, w - 5, h - 4
    cv.hline(px0, px1, py0, "wine", 0)
    cv.vline(px0, py0, py1, "wine", 0)
    cv.hline(px0 + 1, px0 + (px1 - px0) // 2, py1, "wine", 4)
    rng = random.Random(seed)
    x, y = rng.randint(px0 + 4, px0 + 10), py0 + 2  # one broken wine-4 vein at ~30 degrees
    for k in range(6):
        if k != 3:
            cv.px(x + k, y + k // 2, "wine", 4)
    return cv


