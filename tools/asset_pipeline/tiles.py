Cell = tuple[int, int]


class AtlasBuilder:
    """Packs tiles into the atlas and records names, fields, pieces and
    collision. Decor cells are de-duplicated by pixel content; fully
    transparent piece cells are dropped (stored as null)."""

    def __init__(self, cols: int = COLS) -> None:
        self.cols = cols
        self.cells: dict[Cell, Image.Image] = {}
        self.collision: dict[Cell, str] = {}
        self.tiles: dict[str, Cell] = {}
        self.fields: dict[str, dict[str, object]] = {}
        self.pieces: dict[str, dict[str, object]] = {}
        self.edges: dict[str, Cell] = {}
        self._reserved = {pos for pos, _ in LEGACY.values()}
        self._next = 0
        self._dedupe: dict[bytes, Cell] = {}
        # optional L5 occluder plane, passed through to the room builder
        self.foreground: dict[str, object] | None = None

    def _alloc(self) -> Cell:
        while True:
            pos = (self._next % self.cols, self._next // self.cols)
            self._next += 1
            if pos not in self._reserved and pos not in self.cells:
                return pos

    def _put(self, img: Image.Image, collision: str | None, at: Cell | None = None,
             dedupe: bool = False) -> Cell:
        img = img.convert("RGBA")
        assert img.size == (T, T), img.size
        a = np.array(img)
        a[a[..., 3] == 0] = 0
        if a[..., 3].min() not in (0, 255) or not set(np.unique(a[..., 3]).tolist()) <= {0, 255}:
            raise ValueError("tile alpha must be 0 or 255")
        key = a.tobytes()
        if dedupe and collision is None and at is None and key in self._dedupe:
            return self._dedupe[key]
        pos = at if at is not None else self._alloc()
        self.cells[pos] = Image.fromarray(a, "RGBA")
        if collision:
            self.collision[pos] = collision
        if collision is None and at is None:
            self._dedupe.setdefault(key, pos)
        return pos

    def tile(self, name: str, img: Image.Image | Canvas, collision: str | None = None,
             at: Cell | None = None) -> Cell:
        if name in self.tiles:
            raise ValueError(f"duplicate tile name {name!r}")
        im = img.image() if isinstance(img, Canvas) else img
        pos = self._put(im, collision, at)
        self.tiles[name] = pos
        return pos

    def _slice(self, img: Image.Image, collision: str | None, dedupe: bool,
               keep_empty: bool = False) -> list[list[Cell | None]]:
        w, h = img.size
        if w % T or h % T:
            raise ValueError(f"piece size {img.size} is not a multiple of {T}")
        rows: list[list[Cell | None]] = []
        for cy in range(h // T):
            row: list[Cell | None] = []
            for cx in range(w // T):
                sub = img.crop((cx * T, cy * T, cx * T + T, cy * T + T))
                if not keep_empty and np.array(sub)[..., 3].max() == 0:
                    row.append(None)
                    continue
                row.append(self._put(sub, collision, dedupe=dedupe))
            rows.append(row)
        return rows

    def field(self, name: str, img: Image.Image | Canvas, collision: str | None) -> None:
        im = img.image() if isinstance(img, Canvas) else img
        cells = self._slice(im, collision, dedupe=False, keep_empty=True)
        self.fields[name] = {"size": [im.width // T, im.height // T], "cells": cells}

    def piece(self, name: str, img: Image.Image | Canvas, collision: str | None = None) -> None:
        if name in self.pieces:
            raise ValueError(f"duplicate piece name {name!r}")
        im = img.image() if isinstance(img, Canvas) else img
        cells = self._slice(im, collision, dedupe=collision is None)
        self.pieces[name] = {"size": [im.width // T, im.height // T], "cells": cells}

    def edge(self, mask: int, img: Canvas) -> None:
        self.edges[str(mask)] = self._put(img.image(), None, dedupe=True)

    # -- output ------------------------------------------------------------
    def rows(self) -> int:
        return max(p[1] for p in self.cells) + 1

    def save(self) -> None:
        rows = self.rows()
        atlas = Image.new("RGBA", (self.cols * T, rows * T), (0, 0, 0, 0))
        for (x, y), im in self.cells.items():
            atlas.paste(im, (x * T, y * T))
        atlas.save(ATLAS_PNG)

        def cell(c: Cell | None) -> list[int] | None:
            return None if c is None else [c[0], c[1]]

        data: dict[str, object] = {
            "tile_size": T,
            "columns": self.cols,
            "rows": rows,
            "texture": "res://assets/tiles/castle_tiles.png",
            "tiles": {k: cell(v) for k, v in sorted(self.tiles.items())},
            "edges": {k: cell(v) for k, v in sorted(self.edges.items(), key=lambda kv: int(kv[0]))},
            "edge_bits": {"top": EDGE_TOP, "right": EDGE_RIGHT, "bottom": EDGE_BOTTOM, "left": EDGE_LEFT},
            "fields": {k: {"size": v["size"], "cells": [[cell(c) for c in row] for row in v["cells"]]}  # type: ignore[union-attr]
                       for k, v in sorted(self.fields.items())},
            "pieces": {k: {"size": v["size"], "cells": [[cell(c) for c in row] for row in v["cells"]]}  # type: ignore[union-attr]
                       for k, v in sorted(self.pieces.items())},
            "collision": {
                "solid": sorted([list(c) for c, k in self.collision.items() if k == "solid"], key=lambda c: (c[1], c[0])),
                "one_way": sorted([list(c) for c, k in self.collision.items() if k == "one_way"], key=lambda c: (c[1], c[0])),
            },
        }
        if self.foreground is not None:
            data["foreground"] = self.foreground
        with open(ATLAS_JSON, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=1)
            fh.write("\n")
        self._write_tileset()

    def _write_tileset(self) -> None:
        tileset_uid, texture_uid = _existing_uids()
        lines = [f'[gd_resource type="TileSet" format=3 uid="{tileset_uid}"]', "",
                 f'[ext_resource type="Texture2D" uid="{texture_uid}" '
                 f'path="res://assets/tiles/castle_tiles.png" id="1_tiles"]', "",
                 '[sub_resource type="TileSetAtlasSource" id="TileSetAtlasSource_castle"]',
                 'texture = ExtResource("1_tiles")']
        square = "PackedVector2Array(-8, -8, 8, -8, 8, 8, -8, 8)"
        top5 = "PackedVector2Array(-8, -8, 8, -8, 8, -3, -8, -3)"
        for (x, y) in sorted(self.cells, key=lambda c: (c[1], c[0])):
            lines.append(f"{x}:{y}/0 = 0")
            kind = self.collision.get((x, y))
            if kind == "solid":
                lines.append(f"{x}:{y}/0/physics_layer_0/polygon_0/points = {square}")
            elif kind == "one_way":
                lines.append(f"{x}:{y}/0/physics_layer_1/polygon_0/points = {top5}")
                lines.append(f"{x}:{y}/0/physics_layer_1/polygon_0/one_way = true")
        lines += ["", "[resource]",
                  "physics_layer_0/collision_layer = 1",
                  "physics_layer_0/collision_mask = 0",
                  "physics_layer_1/collision_layer = 256",
                  "physics_layer_1/collision_mask = 0",
                  'sources/0 = SubResource("TileSetAtlasSource_castle")', ""]
        os.makedirs(os.path.dirname(TILESET_PATH), exist_ok=True)
        with open(TILESET_PATH, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))


def _existing_uids() -> tuple[str, str]:
    """Keep whatever uids Godot has already assigned (tileset resource and
    the atlas texture's .import), falling back to the historical ones."""
    tileset_uid, texture_uid = TILESET_UID, TEXTURE_UID
    try:
        with open(TILESET_PATH, encoding="utf-8") as fh:
            m = re.search(r'\[gd_resource[^\]]*uid="(uid://[a-z0-9]+)"', fh.read())
            if m:
                tileset_uid = m.group(1)
    except OSError:
        pass
    try:
        with open(ATLAS_PNG + ".import", encoding="utf-8") as fh:
            m = re.search(r'^uid="(uid://[a-z0-9]+)"', fh.read(), re.M)
            if m:
                texture_uid = m.group(1)
    except OSError:
        pass
    return tileset_uid, texture_uid


